export function getCitiesByCountry(country: string): string[] {
  // Проверяем, является ли выбранная страна Россией
  if (country.toLowerCase() === "россия") {
    // Возвращаем список городов для России
    return [
      "Москва",
      "Санкт-Петербург",
      "Новосибирск",
      "Екатеринбург",
      "Нижний Новгород",
      // Другие города России...
    ];
  } else {
    // Если выбрана другая страна, возвращаем пустой список
    return [];
  }
}
